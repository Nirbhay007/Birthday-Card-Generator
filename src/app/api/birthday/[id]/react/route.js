import { NextResponse } from 'next/server';
import { cookies } from 'next/headers';
import prisma from '@/lib/prisma';

/**
 * Viral-loop counters: views, loves, shares — with anti-spam layers:
 * 1. One view / one love per browser (httpOnly cookie) — survives reloads.
 * 2. Shares are recorded as individual ShareEvent rows (channel + source),
 *    deduped per (page, channel, session) for 6 hours. Double-clicks and
 *    repeated clicks on the same channel never inflate the count, while
 *    sharing to a different channel still counts.
 * 3. Per-IP rate limit (best-effort in-memory; mirrors the create route's
 *    budget approach for direct API spam).
 * 4. Fail-open: counter failures never break the celebration page.
 */

const WINDOW_MS = 60_000;
const MAX_PER_WINDOW = 30;
const SHARE_DEDUPE_MS = 6 * 60 * 60 * 1000; // must match lib/shareTracking.js
const hits = new Map();

function throttled(ip) {
    const now = Date.now();
    const arr = (hits.get(ip) || []).filter((t) => now - t < WINDOW_MS);
    arr.push(now);
    hits.set(ip, arr);
    if (hits.size > 5000) hits.delete(hits.keys().next().value);
    return arr.length > MAX_PER_WINDOW;
}

const COUNTS = { viewCount: true, loves: true, shares: true };

const SHARE_CHANNELS = new Set(['whatsapp', 'telegram', 'facebook', 'x', 'copy', 'native', 'other']);
const SHARE_SOURCES = new Set(['post_creation', 'creator_notice', 'card_footer']);

function cleanChannel(value) {
    if (typeof value !== 'string') return 'other';
    const v = value.trim().toLowerCase().slice(0, 32);
    return SHARE_CHANNELS.has(v) ? v : 'other';
}

function cleanSource(value) {
    return typeof value === 'string' && SHARE_SOURCES.has(value) ? value : 'card_footer';
}

// Random per-tab id generated by the client. Not PII — used only to collapse
// repeat share clicks in the same browsing session.
function cleanSessionId(value) {
    return typeof value === 'string' && /^[A-Za-z0-9_-]{8,64}$/.test(value) ? value : null;
}

// Preview guard (defense in depth): POSTs carrying ?preview=1 — or the
// x-preview: 1 header — return current counts without incrementing.
// The client already skips firing in preview mode; this covers direct API
// calls, curl, and future callers that forward the page URL.
function isPreviewRequest(request) {
    try {
        const { searchParams } = new URL(request.url);
        if (searchParams.has('preview')) {
            const v = (searchParams.get('preview') || '').toLowerCase();
            if (v === '' || v === '1' || v === 'true' || v === 'yes' || v === 'on') return true;
        }
    } catch {}
    try {
        const h = (request.headers.get('x-preview') || '').toLowerCase();
        if (h === '1' || h === 'true' || h === 'yes' || h === 'on') return true;
    } catch {}
    return false;
}

/**
 * GET /api/birthday/[id]/react — current counters.
 *
 * Read-only and PII-free. Used by the creator's proof-moment banner so it can
 * show fresh love counts on an otherwise ISR-cached card page.
 */
export async function GET(request, { params }) {
    try {
        const { id } = await params;
        if (!id || typeof id !== 'string' || id.length > 64) {
            return NextResponse.json({ success: false }, { status: 400 });
        }
        const page = await prisma.birthdayPage.findUnique({ where: { id }, select: COUNTS });
        if (!page) return NextResponse.json({ success: false }, { status: 404 });
        return NextResponse.json({ success: true, ...page });
    } catch (error) {
        console.error('React counter read error:', error?.message || error);
        return NextResponse.json({ success: false }, { status: 200 });
    }
}

export async function POST(request, { params }) {
    try {
        const { id } = await params;
        if (!id || typeof id !== 'string' || id.length > 64) {
            return NextResponse.json({ success: false }, { status: 400 });
        }
        const body = await request.json().catch(() => ({}));
        const { type } = body;

        let data = null;
        let share = null;
        if (type === 'view') data = { viewCount: { increment: 1 } };
        else if (type === 'love') data = { loves: { increment: 1 } };
        else if (type === 'share') {
            data = { shares: { increment: 1 } };
            share = {
                channel: cleanChannel(body.channel),
                source: cleanSource(body.source),
                sessionId: cleanSessionId(body.sessionId),
            };
        } else {
            return NextResponse.json({ success: false, error: 'Unknown reaction type' }, { status: 400 });
        }

        const ip = request.headers.get('x-forwarded-for')?.split(',')[0]?.trim() || 'unknown';
        if (throttled(ip)) {
            return NextResponse.json({ success: false, error: 'Slow down' }, { status: 429 });
        }

        if (isPreviewRequest(request)) {
            const page = await prisma.birthdayPage.findUnique({ where: { id }, select: COUNTS }).catch(() => null);
            return NextResponse.json({ success: true, preview: true, ...(page || { viewCount: 0, loves: 0, shares: 0 }) });
        }

        const jar = await cookies();
        // Views + loves: one per browser. Shares use the ShareEvent row +
        // session window below instead.
        const cookieName = type === 'view' ? `bgen-v-${id}` : type === 'love' ? `bgen-l-${id}` : null;
        if (cookieName && jar.get(cookieName)) {
            // Cookie already set — return instantly, skip DB read
            return NextResponse.json({ success: true, duplicate: true });
        }

        // Share dedupe: same page + channel + browser session within 6h is
        // one action. A different channel is a distinct share.
        if (share?.sessionId) {
            const duplicate = await prisma.shareEvent
                .findFirst({
                    where: {
                        pageId: id,
                        channel: share.channel,
                        sessionId: share.sessionId,
                        createdAt: { gte: new Date(Date.now() - SHARE_DEDUPE_MS) },
                    },
                    select: { id: true },
                })
                .catch((err) => {
                    // Table not migrated yet — let the fallback below handle it.
                    if (err?.code === 'P2021') return null;
                    throw err;
                });
            if (duplicate) {
                return NextResponse.json({ success: true, duplicate: true });
            }
        }

        let page;
        if (share) {
            try {
                const [, updated] = await prisma.$transaction([
                    prisma.shareEvent.create({
                        data: {
                            pageId: id,
                            channel: share.channel,
                            source: share.source,
                            sessionId: share.sessionId,
                        },
                    }),
                    prisma.birthdayPage.update({ where: { id }, data, select: COUNTS }),
                ]);
                page = updated;
            } catch (err) {
                // Deployment-order safety: if ShareEvent has not been pushed
                // yet, keep the legacy counter working instead of dropping
                // shares entirely.
                if (err?.code !== 'P2021') throw err;
                console.error('ShareEvent table missing — run "npx prisma db push". Falling back to counter-only share tracking.');
                page = await prisma.birthdayPage.update({ where: { id }, data, select: COUNTS });
            }
        } else {
            page = await prisma.birthdayPage.update({ where: { id }, data, select: COUNTS });
        }

        const res = NextResponse.json({ success: true, ...page });
        if (cookieName) {
            res.cookies.set(cookieName, '1', { httpOnly: true, sameSite: 'lax', maxAge: 31536000, path: '/' });
        }
        return res;
    } catch (error) {
        // Never break the celebration on counter failures (e.g. unknown id)
        console.error('React counter error:', error?.message || error);
        return NextResponse.json({ success: false }, { status: 200 });
    }
}
